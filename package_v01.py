#!/usr/bin/env python3
"""Deterministic release archives for Ashfall v0.1."""
from pathlib import Path
import hashlib, zipfile
root=Path(__file__).resolve().parent
out=root.parent
base=root/'baseline/v75/compiled'
game=root/'game-data'
changed=sorted(p.name for p in game.glob('*.txt') if (base/p.name).read_bytes()!=p.read_bytes())
expect=['menus.txt','quick_strings.txt','scripts.txt','simple_triggers.txt','variable_uses.txt','variables.txt']
assert changed==expect,(changed,expect)

def pack(archive, entries):
    with zipfile.ZipFile(archive,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=8) as z:
        for name,p in sorted(entries,key=lambda t:t[0]):
            info=zipfile.ZipInfo(name,date_time=(2026,11,8,0,0,0))
            info.compress_type=zipfile.ZIP_DEFLATED
            info.external_attr=0o644 << 16
            z.writestr(info,p.read_bytes(),compress_type=zipfile.ZIP_DEFLATED,compresslevel=8)
    with zipfile.ZipFile(archive) as z:
        assert z.testzip() is None
        assert len(z.namelist())==len(set(z.namelist()))
    return archive

pack(out/'烽烟与暗流-v0.1-游戏增量包.zip',
     [('FewerBandits/'+n,game/n) for n in changed] +
     [('安装和说明.md',root/'README_ASHFALL_V01.md'),
      ('实机测试清单.md',root/'tests/实机测试清单.md')])

exclude={'__pycache__','.DS_Store'}
entries=[]
for p in root.rglob('*'):
    if not p.is_file() or any(part in exclude for part in p.parts):continue
    if 'build/compiled/' in p.as_posix():continue # regenerated by build_v01.py
    entries.append(('Ashfall-v0.1/'+p.relative_to(root).as_posix(),p))
pack(out/'烽烟与暗流-v0.1-完整源码.zip',entries)

for archive in (out/'烽烟与暗流-v0.1-游戏增量包.zip',out/'烽烟与暗流-v0.1-完整源码.zip'):
    print(archive, 'bytes=',archive.stat().st_size, 'sha256=',hashlib.sha256(archive.read_bytes()).hexdigest())
print('changed files:',changed,'full-source files:',len(entries))
